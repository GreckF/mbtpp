// Build the online playground in docs/ (served by GitHub Pages):
//   node scripts/build-web.mjs
// compiles src/web to JavaScript and collects the examples.
import { execSync } from "node:child_process";
import { copyFileSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
execSync("moon build --target js", { cwd: root, stdio: "inherit" });
copyFileSync(
  join(root, "_build/js/release/build/web/web.js"),
  join(root, "docs/mbtpp.js"),
);

// examples in a fixed order: the simplest first
const first = ["basic", "vector", "traits", "mbt_types", "proofs", "stlc"];
const names = readdirSync(join(root, "examples"))
  .filter((f) => f.endsWith(".mbtpp"))
  .map((f) => f.slice(0, -".mbtpp".length))
  .sort((a, b) => {
    const ia = first.indexOf(a), ib = first.indexOf(b);
    return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib) || a.localeCompare(b);
  });
const examples = names.map((n) => [
  n,
  readFileSync(join(root, "examples", n + ".mbtpp"), "utf8").replace(/\r\n/g, "\n"),
]);
writeFileSync(
  join(root, "docs/examples.js"),
  "// Generated by scripts/build-web.mjs from examples/.\nexport const examples = " +
    JSON.stringify(examples, null, 1) +
    ";\n",
);
console.log("docs/: mbtpp.js, examples.js (" + names.length + " examples)");
